import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {splitRootSegments} from '../assets/editor-core.mjs';
import {encodeEditorText,decodeEditorText,nameMap} from '../assets/editor-text-codec.mjs';
import {finalDefaultSaveName} from '../assets/editor-save-name-defaults.mjs';

test('new Final save names use current glyph codes; the legacy name reader remains separate',()=>{
 const gameId='srwf-final';
 for(const text of ['경','미나','아무로','크리스']){
  const fresh=encodeEditorText(text,{gameId,kind:'save'});
  assert.deepEqual(fresh,encodeEditorText(text,{gameId,kind:'weapon'}));
  assert.equal(decodeEditorText(fresh,{gameId,kind:'save'}),text);
  assert.equal(decodeEditorText(encodeEditorText(text,{gameId,kind:'hero'}),{gameId,kind:'hero'}),text);
 }
 assert.deepEqual([...encodeEditorText('경',{gameId,kind:'hero'})],[0xf2,0xe2,255]);
 assert.notDeepEqual(encodeEditorText('경',{gameId,kind:'save'}),encodeEditorText('경',{gameId,kind:'hero'}));
});

// Optional private fixtures: hash-named decoded TSR copies prepared from the
// accepted sparse patches. They are never generated by, or stored with, tests.
const fixtureDir=process.env.SRWF_NAME_TSR_DIR;
const names=['레난제스 스타로드','이룸가르트 카자하라','헥토르 매디슨','어윈 도스틴','패트리샤 해크먼','그레이스 우리진','미나 라이클링','린 마오'];
for(const gameId of ['srwf-f','srwf-final'])for(const font of ['a','b','c']){
 const release=JSON.parse(fs.readFileSync(new URL(`../releases/${gameId==='srwf-f'?'srwf-f-20260928-v0-5':'srwf-final-20261005-v0-3'}-${font}.json`,import.meta.url)));
 const file=fixtureDir&&path.join(fixtureDir,`${release.target.sha256}-tsr.bin`);
 test(`${gameId} ${font}: every newly encoded Hangul has ink in the accepted atlas`,{skip:!file||!fs.existsSync(file)},()=>{
  const decoded=new Uint8Array(fs.readFileSync(file)),atlas=splitRootSegments(decoded)[36];
  assert.equal(atlas.bytes.length,2816*32);
  for(const ch of new Set(nameMap(gameId,'save').values())){
   if(!/^[가-힣]$/u.test(ch))continue;
   const encoded=encodeEditorText(ch,{gameId,kind:'save'});
   assert.equal(encoded.length,3);const code=encoded[0]*256+encoded[1];
   assert.ok(code>=(gameId==='srwf-f'?0xeb00:0xec00)&&code<=0xf5ff);
   assert.ok(atlas.bytes.subarray((code-0xeb00)*32,(code-0xeb00)*32+32).some(Boolean),`${ch}: ${code.toString(16)}`);
  }
  if(gameId!=='srwf-final')return;
  const view=new DataView(decoded.buffer,decoded.byteOffset,decoded.byteLength);
  for(let i=0;i<8;i++){
   const row=0x2e0e8+i*64,legacy=view.getUint32(row+16)-0x2021d000;
   assert.ok(legacy>=0&&legacy+14<=decoded.length);
   assert.equal(decodeEditorText(decoded.slice(row+32,row+52),{gameId,kind:'weapon'}),names[i],'the exact matcher points to this current-font name');
   for(const offset of [row,legacy]){
    const bytes=decoded.slice(offset,offset+14);
    for(const faceId of [304+i*2,305+i*2]){
     assert.equal(finalDefaultSaveName(bytes,faceId),names[i]);
     assert.equal(decodeEditorText(bytes,{gameId,kind:'save',faceId}),names[i]);
    }
    assert.equal(finalDefaultSaveName(bytes,304+((i+1)%8)*2),null,'the same bytes do not select another identity');
    const changed=bytes.slice();changed[0]^=1;
    assert.equal(finalDefaultSaveName(changed,304+i*2),null,'a custom mutation is not an exact default');
   }
  }
 });
}
