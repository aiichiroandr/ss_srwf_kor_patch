const bases = [...EDITOR_PROVENANCE_PROFILES, ...STOCK_EDITOR_PROFILES];
const merge = ranges => {
  const out = [];
  for (const range of ranges.map(r => [...r]).sort((a,b) => a[0]-b[0])) {
    const last = out.at(-1);
    if (last && last.every((v,i) => v === range[i])) continue;
    if (last && last[2] === 255 && range[2] === 255 && last[0]+last[1] >= range[0]) last[1] = Math.max(last[0]+last[1], range[0]+range[1])-last[0];
    else out.push(range);
  }
  return Object.freeze(out.map(Object.freeze));
};
export const REWARD_EDITOR_PROFILES = Object.freeze(pins.map(pin => {
  const base = bases.find(p => p.baseTargetSha256 === pin.baseTargetSha256);
  if (!base) throw new Error('Missing reward provenance base');
  return Object.freeze({...base, decodedMasks: merge([...base.decodedMasks,...pin.rewardMasks]), immutableTsrSha256: pin.immutableTsrSha256});
}));
