// Rebuild the cross-game identity allowlist offline. Supply only local approved images.
// Deliberately never writes source images, names, record bytes, or gameplay stats.
const {openAsBlob} = require('node:fs');
const {readFile} = require('node:fs/promises');
const {join} = require('node:path');

async function main() {
const {inspectPatchedImage} = await import('../assets/editor-core.mjs');

const argv=process.argv.slice(2);
if(argv.length!==2)throw Error('Usage: node scripts/editor-f-final-transfer-map.cjs <accepted-f-v0.5a.bin> <accepted-final-v0.3c.bin>');
const lanes=[['srwf-f','srwf-f-20260928-v0-5-a'],['srwf-final','srwf-final-20261005-v0-3-c']];
const views=[];
for(let i=0;i<lanes.length;i++){
 const [gameId,releaseId]=lanes[i];
 const {target}=JSON.parse(await readFile(join(__dirname,'..','releases',`${releaseId}.json`),'utf8'));
 const {view}=await inspectPatchedImage(await openAsBlob(argv[i]),{gameId,targetSize:target.size,targetSha256:target.sha256});
 if(view.provenanceMode!=='accepted'||view.baseTargetSha256!==target.sha256)throw Error(`Not exact approved input: ${releaseId}`);
 views.push(view);
}

const label=s=>s.normalize('NFKC').toLowerCase().replace(/\s+/gu,'');
const indexed=rows=>new Map(rows.filter(r=>r.editable===true&&r.recordKind==='regular'&&r.nameStatus==='decoded'&&r.name&&r.identity).map(r=>[r.recordIndex,r]));
function owners(row){
 return row.owners.map(({unit,entryIndex,slot,ammoSlot,flagNumber,requiresInvestment})=>[unit,entryIndex,slot,ammoSlot,flagNumber,requiresInvestment].join(':')).sort();
}
const allow={};
for(const [kind,key] of [['unit','units'],['pilot','pilots'],['weapon','weapons']]){
 const [f,final]=views.map(view=>indexed(view[key]));
 const pairs={};
 for(const [index,source] of f){
  const target=final.get(index);
  // These are the exact approved images, so use the primary unmodified
  // identity, not a personal P-edit counterpart.
  if(!target||target.identity!==source.identity||label(target.name)!==label(source.name))continue;
  if(kind==='unit'&&['mapIcon','saveUnitKind','saveUnitForm'].some(prop=>source[prop]!==target[prop]))continue;
  if(kind==='pilot'&&[source,target].some(r=>!r.statsValid||r.role||r.aliasIds?.length))continue;
  if(kind==='weapon'){
   const links=owners(source);
   if(!links.length||source.mapType!==target.mapType||[source,target].some(r=>r.unverifiedOwnerUnits.length)||
     links.join('|')!==owners(target).join('|')||source.ownerUnits.some(unit=>!Object.hasOwn(allow.unit,unit)))continue;
  }
  pairs[index]=source.identity.split(':').at(-1);
 }
 allow[kind]=pairs;
 console.error(`${kind}: ${Object.keys(pairs).length} / ${f.size}`);
}
console.log('// Generated by scripts/editor-f-final-transfer-map.cjs from the two pinned approved images.');
console.log('// Each slot needs the exact immutable header digest on both sides. No ROM bytes or names.');
console.log('export const verifiedFinalTransfer = Object.freeze({');
for(const [kind,table] of Object.entries(allow)){
 console.log(`  ${kind}: Object.freeze({`);
 for(const [index,digest] of Object.entries(table))console.log(`    ${index}: '${digest}',`);
 console.log('  }),');
}
console.log('});');
}

main().catch(error=>{ console.error(error.message);process.exitCode=1; });
