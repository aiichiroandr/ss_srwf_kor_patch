# Orphan rows can be reused, without resetting SP or stock crew following them.
a.mark('findfree');a.mov(11,2);a.imm(6,0);a.imm(7,127);a.addi(7,1)
a.mark('free');a.load(2,0,2);a.extw(0,0);a.lit(3,'alice');a.eq(3,0);a.cond('bf','freenext');a.mov(2,1);a.addi(1,3);a.load(1,0,1);a.e(0xc808);a.cond('bt','freenext');a.mov(14,1);a.add(6,1);a.load(1,0,1);a.e(0xc804);a.cond('bt','attach')
a.mark('freenext');a.addi(2,12);a.addi(6,1);a.e(0x4710);a.cond('bf','free')
# Use the original allocator and SP initializer only for a genuinely new row.
a.lit(4,'alice');a.mov(12,1);a.addi(1,2);a.load(1,5,1);a.extb(5,5);a.addi(1,1);a.load(1,6,1);a.extb(6,6);a.e(0x4609);a.e(0x4609);a.imm(0,3);a.e(0x2609);a.call('create');a.extb(0,6);a.imm(3,-1);a.extb(3,3);a.eq(3,6);a.cond('bt','primarynext');a.mul12(6,2);a.add(11,2)
a.mov(12,1);a.addi(1,3);a.load(1,0,1);a.e(0xc9f0);a.e(0xcb08);a.mov(2,1);a.addi(1,3);a.store(0,1,1)
# r6/r2 are caller-saved across fillSP.
a.e(0x2f66);a.e(0x2f26);a.mov(6,4);a.call('fillSP');a.e(0x62f6);a.e(0x66f6)
a.mov(12,1);a.addi(1,9);a.load(1,0,1);a.mov(2,1);a.addi(1,9);a.store(0,1,1)
a.mark('attach');a.mov(2,1);a.addi(1,8);a.imm(0,-1);a.store(0,1,1);a.mov(14,1);a.add(6,1);a.load(1,0,1);a.e(0xcb04);a.store(0,1,1);a.mov(10,1);a.addi(1,8);a.store(6,1,1)
a.mark('primarynext');a.addi(8,12);a.addi(9,1);a.imm(3,127);a.e(0x3936);a.cond('bf','primary')
# Release the 128-byte frame in two aligned halves: an odd R15 between the
# adds lets an interrupt stack onto an odd address (SH-2 address error hang).
a.mark('done');a.addi(15,64);a.addi(15,64);a.mov(13,0);a.test(0,0);a.cond('bt','actorreturn');a.lit(0,'replayPilot');a.bra('restore');a.mark('actorreturn');a.lit(0,'replayActor')
a.mark('restore');a.e(0x61f6);a.e(0x410e);a.e(0x4f16);a.e(0x4f06);a.e(0x4f26)
for r in range(14,0,-1):a.e(0x60f6|r<<8)
