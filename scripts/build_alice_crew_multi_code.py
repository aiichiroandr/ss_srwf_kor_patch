"""Assemble the newly authored ALICE SH-2 crew adapter; contains no game binary.

The generated bytes must match assets/editor-alice-crew-native.mjs. Original
allocator/list-builder addresses are call targets, not extracted game code.
"""
from pathlib import Path
import argparse
import struct,json

def unit_id(value):
 value=int(value)
 if not 1<=value<=511:raise argparse.ArgumentTypeError('unit ID must be 1..511')
 return value
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--out',type=Path,required=True,help='Output directory for the authored code and labels')
parser.add_argument('--unit-ids',default='430,431,432,433')
parser.add_argument('--game-profile',choices=('final','f-v05-a-research'),default='final',
  help='Authored target constants: final (default) or f-v05-a-research (development research only; IP lifetime/face/hook/first-clear/runtime remain unverified and this does not establish F support)')
parser.add_argument('--runtime-prefix-bytes',type=int,choices=(0,32),default=32,
 help='32 avoids the Saturn initialization scratch bytes; 0 reproduces legacy ALCCREW3')
parser.add_argument('--base',type=lambda s:int(s,0),
 help='Explicit, caller-owned HWRAM placement for development linking; does not allocate RAM')
parser.add_argument('--development-only',action='store_true',
  help='Acknowledge that f-v05-a-research only emits uninstalled authored research code, not F runtime support')
args=parser.parse_args();ids=[unit_id(x)for x in args.unit_ids.split(',')]
if args.game_profile=='f-v05-a-research':
 if args.base is None:parser.error('f-v05-a-research requires explicit --base')
 if not args.development_only:parser.error('f-v05-a-research requires --development-only acknowledgment')
 if args.runtime_prefix_bytes!=32:parser.error('f-v05-a-research requires --runtime-prefix-bytes 32')
elif args.base is None:args.base=0x06003300
if not 1<=len(ids)<=4 or len(set(ids))!=len(ids):parser.error('one to four distinct unit IDs required')
if args.base%4 or not 0x06000000<=args.base<=0x060ffc00:parser.error('base must be word-aligned inside HWRAM with a full 1 KiB slot')
ids+= [0]*(4-len(ids))
BASE=args.base
class Asm:
 def __init__(s):s.w=[];s.labels={};s.fix=[]
 def e(s,w):s.w.append(w)
 def mark(s,k):s.labels[k]=2*len(s.w)
 def bra(s,k):s.fix.append(('bra',len(s.w)*2,k));s.e(0);s.e(9)
 def cond(s,op,k):
  # Inverse short branch over one far branch and its delay slot.
  s.e((0x8b00 if op=='bt' else 0x8900)|1);s.bra(k)
 def lit(s,r,k):s.fix.append(('lit',len(s.w)*2,k,r));s.e(0)
 def mov(s,m,n):s.e(0x6003|n<<8|m<<4)
 def imm(s,n,v):s.e(0xe000|n<<8|v&255)
 def addi(s,n,v):s.e(0x7000|n<<8|v&255)
 def add(s,m,n):s.e(0x300c|n<<8|m<<4)
 def load(s,m,n,sz=4):s.e({1:0x6000,2:0x6001,4:0x6002}[sz]|n<<8|m<<4)
 def store(s,m,n,sz=4):s.e({1:0x2000,2:0x2001,4:0x2002}[sz]|n<<8|m<<4)
 def eq(s,m,n):s.e(0x3000|n<<8|m<<4)
 def test(s,m,n):s.e(0x2008|n<<8|m<<4)
 def extb(s,m,n):s.e(0x600c|n<<8|m<<4)
 def extw(s,m,n):s.e(0x600d|n<<8|m<<4)
 def mul12(s,slot,out):s.mov(slot,out);s.add(out,out);s.add(slot,out);s.e(0x4008|out<<8)
 def call(s,label):s.lit(0,label);s.e(0x400b);s.e(9)
 def finish(s):
  for f in s.fix:
   kind,at,k,*args=f;to=s.labels[k]
   if kind=='bra':
    delta=(to-at-4)//2;assert -2048<=delta<2048;s.w[at//2]=0xa000|(delta&4095)
   else:
    r=args[0];delta=(to-(((BASE+at+4)&~3)-BASE))//4;assert 0<=delta<=255;s.w[at//2]=0xd000|r<<8|delta
  return b''.join(struct.pack('>H',w) for w in s.w)
a=Asm()
for _ in range(args.runtime_prefix_bytes//2):a.e(0)
a.mark('actor');a.imm(0,0);a.bra('entry');a.mark('pilot');a.imm(0,1)
a.mark('entry')
for r in range(1,15):a.e(0x2f06|r<<4)
a.e(0x4f22);a.e(0x4f02);a.e(0x4f12);a.e(0x0102);a.e(0x2f16);a.mov(0,13)
# Private per-call flags, never stored into an unknown game field.
a.addi(15,-128);a.mov(15,14);a.mov(14,2);a.imm(0,0);a.imm(7,32)
a.mark('zero');a.store(0,2);a.addi(2,4);a.e(0x4710);a.cond('bf','zero')
a.lit(0,'units');a.load(0,12);a.test(12,12);a.cond('bt','done')
a.lit(0,'pilots');a.load(0,11);a.test(11,11);a.cond('bt','done')
a.mov(12,8);a.imm(9,127);a.addi(9,1)
a.mark('unitloop');a.load(8,0,2);a.extw(0,0);a.test(0,0);a.cond('bt','unitnext')
for i in range(4):a.lit(3,'unit'+str(i));a.eq(3,0);a.cond('bt','unitmatch')
a.bra('unitnext')
a.mark('unitmatch');a.mov(8,1);a.addi(1,16);a.load(1,0,1);a.extb(0,0);a.imm(3,-1);a.extb(3,3);a.eq(3,0);a.cond('bf','unitnext')
a.addi(1,-1);a.load(1,6,1);a.extb(6,6);a.imm(3,127);a.e(0x3636);a.cond('bt','unitnext')
a.mul12(6,10);a.add(11,10);a.load(10,0,2);a.extw(0,0);a.test(0,0);a.cond('bt','unitnext');a.lit(3,'alice');a.eq(3,0);a.cond('bt','unitnext')
a.mov(14,1);a.add(6,1);a.load(1,0,1);a.e(0xcb01);a.store(0,1,1);a.imm(7,5)
a.mark('markchain');a.load(10,0,2);a.extw(0,0);a.lit(3,'alice');a.eq(3,0);a.cond('bt','markalice')
a.mov(14,1);a.add(6,1);a.load(1,0,1);a.e(0xcb02);a.store(0,1,1)
a.mov(10,1);a.addi(1,8);a.load(1,6,1);a.extb(6,6);a.imm(3,127);a.e(0x3636);a.cond('bt','unitnext');a.mul12(6,10);a.add(11,10);a.e(0x4710);a.cond('bf','markchain');a.bra('unitnext')
a.mark('markalice');a.mov(10,1);a.addi(1,3);a.load(1,0,1);a.e(0xc808);a.cond('bt','unitnext');a.mov(14,1);a.add(6,1);a.load(1,0,1);a.e(0xcb04);a.store(0,1,1)
a.mark('unitnext');a.addi(8,30);a.e(0x4910);a.cond('bf','unitloop')
# Unlink only our transient ALICE from humans outside configured crews.
a.mov(11,8);a.mov(14,2);a.imm(7,127);a.addi(7,1)
